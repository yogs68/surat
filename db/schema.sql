CREATE TABLE users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  email VARCHAR(255) NOT NULL,
  name VARCHAR(120) NOT NULL,
  role ENUM('BIDANG','WAKETUM','SEKJEN','BENDUM','EKSEKUTOR','AUDITOR') NOT NULL DEFAULT 'BIDANG',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uniq_users_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE surat (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  no VARCHAR(64) NOT NULL,
  judul VARCHAR(255) NOT NULL,
  bidang VARCHAR(100) NOT NULL,
  ringkasan TEXT NOT NULL,
  status ENUM('DRAFT','MENUNGGU_APPROVAL','REVISI','DITOLAK','DISETUJUI','DIEKSEKUSI','SELESAI') NOT NULL DEFAULT 'DRAFT',
  prioritas ENUM('Rendah','Normal','Tinggi') NOT NULL DEFAULT 'Normal',
  created_by BIGINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uniq_surat_no (no),
  KEY idx_surat_status (status),
  CONSTRAINT fk_surat_created_by FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE lampiran (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  surat_id BIGINT UNSIGNED NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  file_url TEXT NOT NULL,
  file_size INT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_lampiran_surat (surat_id),
  CONSTRAINT fk_lampiran_surat FOREIGN KEY (surat_id) REFERENCES surat(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE approval_steps (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  surat_id BIGINT UNSIGNED NOT NULL,
  step INT NOT NULL,
  role ENUM('BIDANG','WAKETUM','SEKJEN','BENDUM','EKSEKUTOR','AUDITOR') NOT NULL,
  status ENUM('MENUNGGU','DISETUJUI','DITOLAK','REVISI') NOT NULL DEFAULT 'MENUNGGU',
  approver_id BIGINT UNSIGNED NULL,
  note TEXT NULL,
  acted_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uniq_approval_step (surat_id, step),
  KEY idx_approval_status (status),
  CONSTRAINT fk_approval_surat FOREIGN KEY (surat_id) REFERENCES surat(id) ON DELETE CASCADE,
  CONSTRAINT fk_approval_approver FOREIGN KEY (approver_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE audit_logs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  surat_id BIGINT UNSIGNED NOT NULL,
  actor_id BIGINT UNSIGNED NULL,
  action VARCHAR(80) NOT NULL,
  meta JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_audit_surat_time (surat_id, created_at),
  CONSTRAINT fk_audit_surat FOREIGN KEY (surat_id) REFERENCES surat(id) ON DELETE CASCADE,
  CONSTRAINT fk_audit_actor FOREIGN KEY (actor_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
